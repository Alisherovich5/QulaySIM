/** Projects world-110m.json into flat SVG once, at build time rather than in the browser.
 *
 * The destinations map is static geometry: the same 107KB of TopoJSON parsed,
 * meshed and projected on every visit produces the same path every time. Doing
 * it here turns that into a string the bundler can serve and gzip, and removes
 * d3-geo from the runtime — it is only a transitive dependency of the globe,
 * and importing a package nothing declares is how a dependency bump breaks a
 * page nobody was touching.
 *
 * Equirectangular, clipped to 84°N–60°S: Antarctica is not a destination and
 * the far north is mostly ice, and dropping both is what lets the inhabited
 * world fill the panel instead of sitting in a letterboxed band.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { feature, merge } from 'topojson-client'

const W = 1000
const LAT_TOP = 84
const LAT_BOTTOM = -60
const H = Math.round((W * (LAT_TOP - LAT_BOTTOM)) / 360)

const topo = JSON.parse(readFileSync('public/world-110m.json', 'utf8'))

const x = (lon) => ((lon + 180) / 360) * W
const y = (lat) => ((LAT_TOP - lat) / (LAT_TOP - LAT_BOTTOM)) * H
const n = (v) => Math.round(v * 10) / 10

function ring(coords) {
  let d = ''
  let px = null
  let py = null
  for (const [lon, lat] of coords) {
    const cx = n(x(lon))
    const cy = n(y(lat))
    // Points that land on the same tenth of a pixel are not drawable detail.
    if (px === cx && py === cy) continue
    d += (d ? 'L' : 'M') + cx + ' ' + cy
    px = cx
    py = cy
  }
  return d ? d + 'Z' : ''
}

function pathFor(geometry) {
  const polys = geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates
  return polys.map((poly) => poly.map(ring).join('')).join('')
}

const land = merge(topo, topo.objects.countries.geometries)
const landPath = pathFor(land)

/* Centroids in the same space as the path, so a marker is a plain <circle> at
   the stored point and nothing has to project anything at runtime. Area-weighted
   over the largest ring, which keeps an archipelago's pin on its main island
   rather than in the sea between its parts. */
const countries = feature(topo, topo.objects.countries).features
const centroids = {}
for (const f of countries) {
  if (!f.id) continue
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates
  let best = null
  let bestArea = -1
  for (const poly of polys) {
    const outer = poly[0]
    let area = 0
    for (let i = 0, j = outer.length - 1; i < outer.length; j = i++) {
      area += outer[j][0] * outer[i][1] - outer[i][0] * outer[j][1]
    }
    area = Math.abs(area / 2)
    if (area > bestArea) {
      bestArea = area
      best = outer
    }
  }
  if (!best) continue
  let sx = 0
  let sy = 0
  for (const [lon, lat] of best) {
    sx += lon
    sy += lat
  }
  centroids[f.id] = [n(x(sx / best.length)), n(y(sy / best.length))]
}

const out = `/* GENERATED by scripts/build-world-map.mjs — do not edit.
 *
 * Equirectangular projection of public/world-110m.json, clipped to
 * ${LAT_TOP}°N–${Math.abs(LAT_BOTTOM)}°S, in a ${W}x${H} space. Regenerate with:
 *   node scripts/build-world-map.mjs
 */

export const MAP_WIDTH = ${W}
export const MAP_HEIGHT = ${H}

/** The land silhouette, as one path. */
export const LAND_PATH =
  '${landPath}'

/** Numeric ISO 3166-1 code -> [x, y] in the same space. See lib/isoNumeric. */
export const CENTROIDS: Record<string, [number, number]> = ${JSON.stringify(centroids)}
`
writeFileSync('src/data/world-map.generated.ts', out)
console.log(
  `yozildi: src/data/world-map.generated.ts — ${W}x${H}, yo'l ${(landPath.length / 1024).toFixed(1)} KB, ${Object.keys(centroids).length} markaz`,
)
