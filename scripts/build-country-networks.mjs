/**
 * The networks each destination's eSIM actually roams on, from the wholesaler.
 *
 * Every destination page used to be the same 161 words with the country's name
 * swapped in — 214 pages a search engine reads as one page repeated, which is
 * the definition of thin content and drags the whole domain down with it.
 *
 * This is the first thing that is genuinely different per country and is also
 * true: esimaccess publishes, per package, the operators the profile attaches
 * to and whether each carries 5G. Turkey is Turkcell, Vodafone and Türk
 * Telekom; Georgia is Magti on 4G and Beeline on 5G. Nothing here is written by
 * hand, so nothing here can be invented.
 *
 * Regenerate when the supplier catalogue changes:
 *   node scripts/build-country-networks.mjs <facts.json>
 * where facts.json is dumped from the API container — see docs in the commit.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const source = process.argv[2]
if (!source) {
  console.error("manba fayl kerak: node scripts/build-country-networks.mjs <facts.json>")
  process.exit(1)
}

const raw = JSON.parse(readFileSync(source, 'utf8'))
const out = {}
for (const [iso2, entry] of Object.entries(raw)) {
  const operators = Object.entries(entry.ops || {})
    .map(([name, network]) => ({ name, network: String(network || '').toUpperCase() }))
    // Stable order, so a regenerated file has no spurious diff.
    .sort((a, b) => a.name.localeCompare(b.name))
  if (operators.length) out[iso2.toUpperCase()] = operators
}

const body = Object.entries(out)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([iso2, ops]) => `  ${iso2}: ${JSON.stringify(ops)},`)
  .join('\n')

writeFileSync(
  'src/lib/country-networks.generated.ts',
  `// Generated by scripts/build-country-networks.mjs — do not edit by hand.\n` +
    `// Source: esimaccess package catalogue (locationNetworkList).\n\n` +
    `export interface CountryNetwork {\n  name: string\n  network: string\n}\n\n` +
    `export const COUNTRY_NETWORKS: Record<string, CountryNetwork[]> = {\n${body}\n}\n`,
)
console.log(`yozildi: ${Object.keys(out).length} davlat`)
